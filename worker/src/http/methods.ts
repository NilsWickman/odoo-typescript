/** models.py:214-215: a classmethod or staticmethod of BaseModel (`method == getattr(model, name)`). */
export const CLASS_METHODS = new Set(["is_transient"]);

/**
 * `call_kw(request.env[model], method, args, kwargs)` (dataset.py:251-255 -> model.py:31-75):
 * - private names (`_x`) raise AccessError (models.py:207-209);
 * - `kwargs['context']` REPLACES the environment context (model.py:51-57, PORTING_odoo.md section 1);
 * - a method that is not registered raises NotPorted: whether Odoo would answer AttributeError
 *   ("The method 'm.f' does not exist", models.py:214) cannot be known without the Python class, so no guess.
 */
export async function callKw(env: Environment, model: string, method: string, args: unknown[], kwargs: Record<string, unknown>, opts: { rpc?: boolean } = {}): Promise<unknown> {
  if (method.startsWith("_") || UNSAFE_ATTRIBUTES.has(method)) {
    throw new AccessError(`Private methods (such as '${model}.${method}') cannot be called remotely.`);
  }
  if (CLASS_METHODS.has(method)) throw new AccessError(`The method '${model}.${method}' cannot be called remotely.`);
  if (BASE_PRIVATE.has(method) || MODEL_PRIVATE[method]?.includes(model)) {
    throw new AccessError(`Private methods (such as '${model}.${method}') cannot be called remotely.`);
  }
  // a custom model (B4): BaseModel's methods, registered under CUSTOM_MODEL (src/web/read_methods.ts)
  const registered = lookupMethod(model, method) ?? (env.reg.models.get(model)?.custom ? lookupMethod(CUSTOM_MODEL, method) : null);
  // models.py:211-214: names no class of the Odoo source defines (checked with grep over odoo/ at dd5d3718) do not
  // exist on any model
  if (registered === null && ABSENT_METHODS.has(method)) throw new OdooError("builtins.AttributeError", `The method '${model}.${method}' does not exist`);
  if (registered === null && !(await methodExists(env, model, method))) throw new OdooError("builtins.AttributeError", `The method '${model}.${method}' does not exist`);
  if (registered === null) throw new NotPorted(`call_kw ${model}.${method} is not registered (src/web, src/models)`);

  let ids: number[] | null = null;
  let rest = args;
  if (!registered.apiModel && !registered.rawArgs) {
    const [first, ...others] = args;
    rest = others;
    if (typeof first === "number") ids = [first];
    else if (Array.isArray(first) && first.every((x): x is number => typeof x === "number")) ids = first;
    else if (first === undefined || first === false || first === null) ids = [];
    else throw new OdooError("builtins.TypeError", `expected record ids as first argument of ${model}.${method}`);
  }
  const kw = { ...kwargs };
  const rawContext = kw["context"];
  delete kw["context"];
  let context: Context = {};
  if (typeof rawContext === "object" && rawContext !== null && !Array.isArray(rawContext)) context = rawContext as Context;
  else if (rawContext !== undefined && rawContext !== null && rawContext !== false) {
    throw new OdooError("builtins.TypeError", "context must be a dict");
  }
  // model.py:52-57 carry website_id/host_id over from the request context; router.py:389 sets host_id on every
  // request (ir_http.py:256-310 `_get_host_id_from_domain`)
  // the RPC services run without a request (router.py:143-144): their environment has no host_id to carry over
  if (!opts.rpc && (!("host_id" in context) || !context["host_id"])) {
    const hostId = env.context["host_id"] ?? await hostIdFromDomain(env);
    if (hostId) context = { ...context, host_id: hostId };
  }
  const lang = context["lang"];
  if (typeof lang === "string" && lang !== "" && lang !== "en_US") await ensureRegistryLang(env.cr, env.reg, lang);
  return registered.fn(env.withContext(context), ids, rest, kw, model);
}

function normalizeDomainHost(raw: string): string {
  const trimmed = raw.trim();
  if (!trimmed) return "";
  try {
    return new URL(trimmed.includes("://") ? trimmed : `http://${trimmed}`).host.toLowerCase();
  } catch {
    return trimmed.replace(/^https?:\/\//i, "").split("/")[0]!.toLowerCase();
  }
}

/**
 * ir_http.py:256-310 `_get_host_id_from_domain`: the website whose domain matches the request host, else (port
 * ignored) the same, else the first website by (sequence, id).
 */
export async function hostIdFromDomain(env: Environment): Promise<number | false> {
  // `@api.ormcache('domain_name')` (ir_http.py:256-258), kept in the registry (src/orm/signaling.ts)
  const rows = await registryCached(env.cr, "website _get_host_id_from_domain",
    async () => (await env.cr.query<{ id: number; domain: string | null }>("SELECT id, domain FROM website ORDER BY sequence, id")).rows);
  if (rows.length === 0) return false;
  const req = requestOfCursor(env.cr);
  const reqHost = normalizeDomainHost(req ? (req.baseLocation || req.url.host) : "");
  if (reqHost !== "") {
    const reqHostname = reqHost.split(":")[0]!;
    const exact = rows.find((r) => r.domain && normalizeDomainHost(r.domain) === reqHost);
    if (exact !== undefined) return exact.id;
    const byName = rows.find((r) => r.domain && normalizeDomainHost(r.domain).split(":")[0] === reqHostname);
    if (byName !== undefined) return byName.id;
  }
  return rows[0]?.id ?? false;
}
