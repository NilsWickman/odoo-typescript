#!/usr/bin/env python3
"""Generates the data modules of src/models/ from the Odoo source tree and the reference's Python packages
(PORTING_odoo.md rulings O4 and O5: data read from odoo/ and from installed dependency packages is allowed with a
committed generator and a citation). Run from worker/ with the harness venv:

    ../.venv/bin/python src/models/gen_tables.py

Outputs (committed):
  src/models/avatar_placeholders.ts   the five placeholder PNGs of odoo/odoo/addons/base/static/img (avatar_mixin.py:92,
                                      res_partner.py:450-459), base64, so `_avatar_get_placeholder` works without a filesystem
  src/models/partner_identifiers.ts   ADDITIONAL_IDENTIFIERS_METADATA and TIN_METADATA of odoo/odoo/tools/partner_identifiers.py
                                      (res_partner.py:1635 `_compute_available_additional_identifiers_metadata`); callables keep
                                      their `__name__` because Odoo serializes them with repr() (harness N3)
This file belongs with gen/ (stream G); it lives here until the orchestrator moves it.
"""
import base64
import json
import os
import re
import sys
import types

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
ODOO = os.path.join(ROOT, "odoo")
sys.path.insert(0, ODOO)

HEADER = "// GENERATED by src/models/gen_tables.py from %s. Do not edit.\n"


def ts_string(s):
    return json.dumps(s, ensure_ascii=False)


def gen_placeholders():
    files = ["avatar_grey.png", "avatar_placeholder_company.png", "avatar_placeholder_delivery.png",
             "avatar_placeholder_invoice.png", "avatar_placeholder_other.png"]
    out = [HEADER % "odoo/odoo/addons/base/static/img/avatar_*.png",
           "/** base64 of each placeholder image, keyed by its `_avatar_get_placeholder_path` (avatar_mixin.py:89, res_partner.py:450). */",
           "export const PLACEHOLDERS: Readonly<Record<string, string>> = {"]
    for f in files:
        with open(os.path.join(ODOO, "odoo/addons/base/static/img", f), "rb") as fh:
            out.append('  "base/static/img/%s": %s,' % (f, ts_string(base64.b64encode(fh.read()).decode())))
    out.append("};")
    with open(os.path.join(HERE, "avatar_placeholders.ts"), "w") as fh:
        fh.write("\n".join(out) + "\n")


def gen_identifiers():
    import odoo  # noqa: F401  (sets up odoo.tools)
    import odoo.tools.translate  # noqa: F401
    import odoo.tools.partner_identifier_validation  # noqa: F401
    # partner_identifiers imports two constants from base/models/res_country, which imports base/models/res_partner,
    # which imports partner_identifiers: the circle only resolves inside a full registry load. Provide the constants.
    src_rc = open(os.path.join(ODOO, "odoo/addons/base/models/res_country.py")).read()
    stub = types.ModuleType("odoo.addons.base.models.res_country")
    for name in ("FR_AND_OVERSEAS_TERRITORIES", "SEPA_COUNTRIES"):
        m = re.search(r"^%s\s*=\s*(\[.*?\]|\(.*?\)|\{.*?\})" % name, src_rc, re.S | re.M)
        setattr(stub, name, eval(m.group(1)))  # noqa: S307 (source literal of the Odoo tree)
    import odoo.addons.base.models  # noqa: F401
    sys.modules["odoo.addons.base.models.res_country"] = stub
    from odoo.tools import partner_identifiers as pi

    def conv(o):
        if callable(o):
            return {"__function__": o.__name__}
        if type(o).__name__ == "LazyGettext":
            # resolved at read time with env._() (res_partner.py:1655); en_US is the source string
            return {"__lazy__": o._source}
        if isinstance(o, dict):
            return {k: conv(v) for k, v in o.items()}
        if isinstance(o, (list, tuple, set, frozenset)):
            return [conv(v) for v in o]
        return o

    def ts_value(o, indent):
        pad = "  " * indent
        if isinstance(o, dict):
            if "__function__" in o:
                return "{ kind: \"function\", name: %s }" % ts_string(o["__function__"])
            if "__lazy__" in o:
                return "{ kind: \"lazy\", source: %s }" % ts_string(o["__lazy__"])
            items = ["%s  %s: %s" % (pad, ts_string(k), ts_value(v, indent + 1)) for k, v in o.items()]
            return "{\n" + ",\n".join(items) + "\n" + pad + "}"
        if isinstance(o, list):
            return "[" + ", ".join(ts_value(v, indent) for v in o) + "]"
        if isinstance(o, bool):
            return "true" if o else "false"
        if isinstance(o, (int, float)):
            return repr(o)
        if isinstance(o, str):
            return ts_string(o)
        if o is None:
            return "null"
        raise TypeError(repr(o))

    out = [HEADER % "odoo/odoo/tools/partner_identifiers.py",
           "import type { IdentifierMetadata } from \"./identifiers_types.ts\";",
           "",
           "/** `ADDITIONAL_IDENTIFIERS_METADATA` (partner_identifiers.py:479), in source order. */",
           "export const ADDITIONAL_IDENTIFIERS_METADATA: Readonly<Record<string, IdentifierMetadata>> = %s;" % ts_value(conv(pi.ADDITIONAL_IDENTIFIERS_METADATA), 0),
           "",
           "/** `TIN_METADATA` (partner_identifiers.py:56). */",
           "export const TIN_METADATA: Readonly<Record<string, IdentifierMetadata>> = %s;" % ts_value(conv(pi.TIN_METADATA), 0),
           ""]
    with open(os.path.join(HERE, "partner_identifiers.ts"), "w") as fh:
        fh.write("\n".join(out))



if __name__ == "__main__":
    gen_placeholders()
    gen_identifiers()
    print("ok")
