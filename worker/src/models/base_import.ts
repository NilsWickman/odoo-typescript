interface Suggestion { field_path: string[]; distance?: number }

/** base_import.py:833-982 `_get_mapping_suggestion`. */
function mappingSuggestion(env: Environment, header: string, tree: readonly TreeField[], headerTypes: readonly string[], mapping: Readonly<Record<string, string>>): Suggestion | null {
  if (!tree.length) return null;
  const saved = mapping[header.toLowerCase()];
  if (saved) return { field_path: saved.split("/"), distance: -1 };
  if (!header.includes("/")) {
    const h = casefold(header);
    for (const field of tree) {
      if (h === casefold(field.name) || h === casefold(field.string)) return { field_path: [field.name], distance: 0 };
      const en = fieldStringEn(env, field.model_name, field.name);
      if (en !== undefined && h === casefold(en)) return { field_path: [field.name], distance: 0 };
    }
    const filtered = filterFieldsByTypes(tree, headerTypes);
    if (!filtered.length) return null;
    let minDist = 1;
    let minField: string | false = false;
    for (const field of filtered) {
      const d = [1 - sequenceRatio(h, casefold(field.name)), 1 - sequenceRatio(h, casefold(field.string))];
      const en = fieldStringEn(env, field.model_name, field.name);
      if (en) d.push(1 - sequenceRatio(h, casefold(en)));
      const cur = Math.min(...d);
      if (cur < minDist) { minField = field.name; minDist = cur; }
    }
    return minDist < FUZZY_MATCH_DISTANCE && minField ? { field_path: [minField], distance: minDist } : null;
  }
  const path: string[] = [];
  let sub: readonly TreeField[] = tree;
  for (const part of header.split("/")) {
    const m = mappingSuggestion(env, part.trim(), sub, headerTypes, {});
    if (!m) return null;
    const name = m.field_path[0]!;
    sub = sub.find((f) => f.name === name)!.fields;
    path.push(name);
  }
  return { field_path: path };
}

