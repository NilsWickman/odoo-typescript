/** odoo/tools/mimetypes.py guess_mimetype, for the signatures that decide the reader here. */
function guessMimetype(data: Uint8Array): string {
  if (data.length >= 4 && data[0] === 0x50 && data[1] === 0x4b && data[2] === 0x03 && data[3] === 0x04) return "application/zip";
  if (data.length >= 8 && data[0] === 0xd0 && data[1] === 0xcf && data[2] === 0x11 && data[3] === 0xe0) return "application/vnd.ms-excel";
  return "text/plain";
}

const MIMETYPE_TO_READER: Readonly<Record<string, string>> = {
  "text/csv": "csv", "application/vnd.ms-excel": "xls",
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": "xlsx", "application/vnd.oasis.opendocument.spreadsheet": "ods",
};

/** base_import.py:376-419 `_read_file` and :609-674 `_read_csv`. Mutates `options` like Odoo. */
function readFile(env: Environment, rec: ImportRow, options: Record<string, unknown>): string[][] {
  const data = rec.file === null ? new Uint8Array() : new Uint8Array(rec.file);
  const tries: (string | undefined)[] = [MIMETYPE_TO_READER[guessMimetype(data)], MIMETYPE_TO_READER[rec.file_type ?? ""]];
  if (rec.file_name) {
    // os.path.splitext: the last dot not leading the name
    let stem = rec.file_name.slice(rec.file_name.lastIndexOf("/") + 1);
    while (stem.startsWith(".")) stem = stem.slice(1);
    const dot = stem.lastIndexOf(".");
    tries.push(dot >= 0 ? stem.slice(dot + 1) : "");
  }
  for (const ext of tries) {
    if (!ext) continue;
    if (ext === "csv") return readCsv(env, data, options);
    if (ext === "xls" || ext === "xlsx" || ext === "ods") throw new NotPorted(`import of ${ext} files`);
  }
  // `"{}".format(self.file_type)`: an empty Char field reads False
  throw new OdooError("odoo.exceptions.UserError", `Unsupported file format "${rec.file_type === null ? "False" : rec.file_type}", import only supports CSV, ODS, XLS and XLSX`);
}

function readCsv(env: Environment, data: Uint8Array, options: Record<string, unknown>): string[][] {
  if (!data.length) return [];
  let encoding = typeof options["encoding"] === "string" ? options["encoding"] : "";
  const guessed = !encoding;
  if (!encoding) encoding = options["encoding"] = detectEncoding(data);
  let text: string;
  try {
    text = decode(data, encoding);
  } catch (e) {
    if (e instanceof NotPorted) throw e;
    throw new ImportValidationError(guessed
      ? translate(env, `There was an issue decoding the file using encoding “${encoding}”.\nThis encoding was automatically detected.`)
      : translate(env, `There was an issue decoding the file using encoding “${encoding}”.\nThis encoding was manually selected.`));
  }
  const quoting = String(options["quoting"] ?? '"');
  let separator = typeof options["separator"] === "string" ? options["separator"] : "";
  if (!separator) {
    separator = ",";
    const sniffed = sniffSeparator(text, quoting);
    if (sniffed !== null) separator = options["separator"] = sniffed;
  }
  if ([...quoting].length !== 1) throw new ImportValidationError(translate(env, "Error while importing records: Text Delimiter should be a single character."));
  if ([...separator].length !== 1) throw new NotPorted("csv delimiter of more than one character (TypeError)");
  return csvRead(text, separator, quoting).filter((row) => row.some((x) => x.trim()));
}

