function convertImportData(env: Environment, rec: ImportRow, fields: readonly (string | false)[], options: Record<string, unknown>): [string[][], string[]] {
  const importFields: string[] = [];
  for (const f of fields) {
    if (!f) continue;
    if (f.includes(LANGUAGE_SEPARATOR)) throw new NotPorted("import of translated columns (field@lang)");
    importFields.push(f); // duplicates are kept for concatenation (_handle_multi_mapping)
  }
  if (!importFields.length) throw new ImportValidationError(translate(env, "You must configure at least one field to import"));
  let rows = readFile(env, rec, { ...options });
  if ((rows[0]?.length ?? 0) !== fields.length) {
    throw new ImportValidationError(translate(env, `Error while importing records: all rows should be of the same size, but the title row has ${fields.length} entries while the first row has ${rows[0]?.length ?? 0}. You may need to change the separator character.`));
  }
  if (options["has_headers"]) rows = rows.slice(1);
  const data: string[][] = [];
  for (const row of rows) {
    let has = false;
    const out: string[] = [];
    row.forEach((value, i) => {
      if (!fields[i]) return;
      if (value) has = true;
      out.push(value);
    });
    if (has) data.push(out);
  }
  const skip = typeof options["skip"] === "number" ? options["skip"] : 0;
  return [data.slice(skip), importFields];
}

