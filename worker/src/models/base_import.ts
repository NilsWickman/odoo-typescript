function filterFieldsByTypes(tree: readonly TreeField[], headerTypes: readonly string[]): TreeField[] {
  const out: TreeField[] = [];
  for (const f of tree) {
    if (f.fields.length) out.push({ ...f, fields: filterFieldsByTypes(f.fields, headerTypes) });
    else if (headerTypes.includes(f.type)) out.push(f);
  }
  return out;
}

