/** base_import.py:1310-1337 `_remove_currency_symbol`. */
async function removeCurrencySymbol(env: Environment, value0: string): Promise<string | false> {
  let value = value0.trim();
  let negative = false;
  if (value.startsWith("(") && value.endsWith(")")) { value = value.slice(1, -1); negative = true; }
  const split = value.split(/([+-]?[0-9.,]+)/).filter((g) => g);
  const isNum = (s: string): boolean => /[+-]?[0-9.,]+/.test(s);
  if (split.length > 2) return false;
  if (split.length === 1) return isNum(split[0]!) ? (negative ? "-" + split[0] : split[0]!) : false;
  if (split.length === 0) return false;
  const currencyIndex = isNum(split[0]!) ? 1 : 0;
  const found = await env.model("res.currency").search(cond("symbol", "=", split[currencyIndex]!.trim()));
  if (found.length) { const v = split[(currencyIndex + 1) % 2]!; return negative ? "-" + v : v; }
  return false;
}

